# ======================================
# Rules for Declering Variable  :-
# ======================================
# ================================================================================
# Rule 1 :- Variable name only contains Characters, numbers and Underscore ("_").
# ================================================================================

# Example :- 

# Valid Examples:-

# student = "Sagar"
# student_name = "Sakshi"
# marks1 = 85
# subject_2 = "Python"
# total_marks = 450



# Invalid Examples with Reasons:-

# 1student = "Sagar"
# Reason: Variable name cannot start with a number.

# student@name = "Sakshi"
# Reason: Special characters like @ are not allowed.

# total-marks = 450
# Reason: Hyphen (-) is not allowed.

# student name = "Nidhi"
# Reason: Spaces are not allowed in variable names.

# marks% = 90
# Reason: Special character % is not allowed.


# =====================================================================================================================
# Rule 2 :- The variable name does not contain any special character, and it only starts with a character.
# =====================================================================================================================

# Valid Examples :-

# name = "Neha"
# _student = "Riya"
# marks_1 = 90
# _roll_number = 101
# student2 = "Saloni"
 
 
 
# Invalid Examples with Reasons :-

# 2name = "Neha"
# Reason: Variable name cannot start with a number.

# 9student = "Riya"
# Reason: Variable name cannot start with a digit.

# @name = "Saloni"
# Reason: Variable name cannot start with a special character.

# #marks = 90
# Reason: Special character # is not allowed.


# ===============================================================
# Rule 3 :- Python keywords cannot be used as variable names.
# ===============================================================

# Valid Examples :-

# my_class = "Python"
# student_for = 10
# return_value = 100
# class_name = "AIML"
# if_condition = True



# Invalid Examples with Reasons :-

# if = 10
# Reason: 'if' is a reserved Python keyword.

# else = 20
# Reason: 'else' is a reserved Python keyword.

# for = 30
# Reason: 'for' is a reserved Python keyword.

# while = 40
# Reason: 'while' is a reserved Python keyword.

# class = "Python"
# Reason: 'class' is a reserved Python keyword.

# return = 50
# Reason: 'return' is a reserved Python keyword.


# =======================================================
# Rule 4 :- Variable names are case-sensitive.
# =======================================================

#  Examples :-

# name = "Sakshi"
# Name = "Nidhi"
# NAME = "Sagar"

# print(name)
# print(Name)
# print(NAME)

# ====================================================
# Rule 5 :- Variable names should be meaningful.
# ====================================================
# Recommended Examples :-

# student_name = "Namrata"
# student_age = 19
# total_marks = 450
# college_name = "IES College"



# Not Recommended Examples :-

# x = "Namrata"
# a = 19
# b = 450
# c = "IES College"

# Reason: These names do not clearly describe
# the purpose of the variables.


# Note: The examples in Rule 5 are technically valid, not invalid

# ==========================================
# Conclusion
# ==========================================

# Variables are used to store data in Python.
# Variable names should follow Python naming rules.
# Always use meaningful variable names.
# Python variable names are case-sensitive.

